import dotenv from 'dotenv';
import oracledb from 'oracledb';

dotenv.config({ path: new URL('../.env', import.meta.url) });

const cadenaConexion = process.env.BD_CADENA_CONEXION;
const formatoFilas = { outFormat: oracledb.OUT_FORMAT_OBJECT };
const catalogos = [
  { tabla: 'JORNADA', identificador: 'ID_JORNADA', columnas: ['ID_JORNADA', 'NOMBRE', 'ESTADO'] },
  { tabla: 'RUTA', identificador: 'ID_RUTA', columnas: ['ID_RUTA', 'NOMBRE', 'DESCRIPCION', 'ESTADO'] },
  { tabla: 'PROVEEDOR', identificador: 'ID_PROVEEDOR', columnas: ['ID_PROVEEDOR', 'NOMBRE', 'NIT', 'TELEFONO', 'DIRECCION', 'ESTADO'] },
];

async function conectar(usuario, contrasena) {
  return oracledb.getConnection({ user: usuario, password: contrasena, connectString: cadenaConexion });
}

async function confirmarDestino(conexion) {
  const resultado = await conexion.execute(
    `SELECT SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS ESQUEMA,
            SYS_CONTEXT('USERENV', 'CON_NAME') AS PDB FROM DUAL`, [], formatoFilas,
  );
  if (resultado.rows[0].ESQUEMA !== 'DB_PANADERIA' || resultado.rows[0].PDB !== 'XEPDB1') {
    throw new Error('El destino no es DB_PANADERIA en XEPDB1.');
  }
}

const origen = await conectar(process.env.BD_USUARIO, process.env.BD_CONTRASENA);
const destino = await conectar(process.env.BD_USUARIO_NUEVO, process.env.BD_CONTRASENA_NUEVO);
try {
  await confirmarDestino(destino);
  for (const catalogo of catalogos) {
    const filasOrigen = await origen.execute(
      `SELECT ${catalogo.columnas.join(', ')} FROM ${catalogo.tabla} ORDER BY ${catalogo.identificador}`,
      [], formatoFilas,
    );
    for (const fila of filasOrigen.rows) {
      const existente = await destino.execute(
        `SELECT ${catalogo.identificador} FROM ${catalogo.tabla} WHERE ${catalogo.identificador} = :identificador`,
        { identificador: fila[catalogo.identificador] }, formatoFilas,
      );
      if (!existente.rows.length) {
        const binds = Object.fromEntries(catalogo.columnas.map(columna => [columna.toLowerCase(), fila[columna]]));
        await destino.execute(
          `INSERT INTO ${catalogo.tabla} (${catalogo.columnas.join(', ')})
           VALUES (${catalogo.columnas.map(columna => `:${columna.toLowerCase()}`).join(', ')})`,
          binds,
        );
      }
    }
  }
  await destino.commit();
  for (const catalogo of catalogos) {
    await destino.execute(
      `ALTER TABLE ${catalogo.tabla} MODIFY (${catalogo.identificador} GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))`,
    );
  }
  console.log('Catálogos operativos sincronizados en DB_PANADERIA.');
} catch (error) {
  await destino.rollback();
  throw error;
} finally {
  await origen.close();
  await destino.close();
}
