-- Ejecutar DESPUES de 01_tablas_originales.sql en un esquema nuevo Oracle 21c XE.
-- No ejecutar repetidamente: crea objetos nuevos y altera tablas existentes.
-- Cambios derivados de los requisitos adicionales sobre perfiles, permisos y operaciones.

-- Perfiles configurables: un usuario puede pertenecer a varios perfiles.
CREATE TABLE ROL (
 ID_ROL NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 NOMBRE VARCHAR2(60) NOT NULL UNIQUE,
 DESCRIPCION VARCHAR2(250),
 ESTADO CHAR(1) DEFAULT 'A' NOT NULL CHECK (ESTADO IN ('A','I'))
);
CREATE TABLE PERMISO (
 ID_PERMISO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 CODIGO VARCHAR2(80) NOT NULL UNIQUE,
 DESCRIPCION VARCHAR2(250) NOT NULL
);
CREATE TABLE ROL_PERMISO (
 ID_ROL NUMBER NOT NULL REFERENCES ROL(ID_ROL),
 ID_PERMISO NUMBER NOT NULL REFERENCES PERMISO(ID_PERMISO),
 CONSTRAINT PK_ROL_PERMISO PRIMARY KEY(ID_ROL,ID_PERMISO)
);
CREATE TABLE USUARIO_ROL (
 ID_USUARIO NUMBER NOT NULL REFERENCES USUARIO(ID_USUARIO),
 ID_ROL NUMBER NOT NULL REFERENCES ROL(ID_ROL),
 CONSTRAINT PK_USUARIO_ROL PRIMARY KEY(ID_USUARIO,ID_ROL)
);
-- USUARIO.TIPO se conserva por compatibilidad con el diseño original; la
-- autorización se realizará mediante USUARIO_ROL -> ROL_PERMISO -> PERMISO.

-- Historial explícito de solicitudes de cancelación.
CREATE TABLE SOLICITUD_CANCELACION (
 ID_SOLICITUD NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ID_PEDIDO NUMBER NOT NULL REFERENCES PEDIDO(ID_PEDIDO),
 ID_USUARIO_SOLICITA NUMBER NOT NULL REFERENCES USUARIO(ID_USUARIO),
 FECHA_SOLICITUD TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 MOTIVO VARCHAR2(300) NOT NULL,
 ESTADO VARCHAR2(15) DEFAULT 'PENDIENTE' NOT NULL
   CHECK (ESTADO IN ('PENDIENTE','APROBADA','RECHAZADA')),
 ID_USUARIO_RESUELVE NUMBER REFERENCES USUARIO(ID_USUARIO),
 FECHA_RESOLUCION TIMESTAMP,
 OBSERVACION_RESOLUCION VARCHAR2(300)
);

-- La producción requiere estados explícitos y vínculo opcional con pedidos.
ALTER TABLE PRODUCCION ADD (
 ID_PEDIDO NUMBER REFERENCES PEDIDO(ID_PEDIDO),
 ESTADO VARCHAR2(25) DEFAULT 'PLANIFICADA' NOT NULL,
 FECHA_CONFIRMACION TIMESTAMP,
 ID_USUARIO_CONFIRMA NUMBER REFERENCES USUARIO(ID_USUARIO),
 ORIGEN VARCHAR2(12) DEFAULT 'MANUAL' NOT NULL,
 CONSTRAINT CHK_PROD_ESTADO_F1 CHECK
  (ESTADO IN ('PLANIFICADA','AUTORIZADA','EN_PRODUCCION','FINALIZADA','CANCELADA')),
 CONSTRAINT CHK_PROD_ORIGEN_F1 CHECK (ORIGEN IN ('MANUAL','PEDIDO'))
);

-- Registro de despacho y entregas, independiente de la ruta maestra.
CREATE TABLE DESPACHO (
 ID_DESPACHO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ID_PEDIDO NUMBER NOT NULL REFERENCES PEDIDO(ID_PEDIDO),
 ID_RUTA NUMBER REFERENCES RUTA(ID_RUTA),
 ID_USUARIO_DESPACHA NUMBER NOT NULL REFERENCES USUARIO(ID_USUARIO),
 ID_USUARIO_PILOTO NUMBER REFERENCES USUARIO(ID_USUARIO),
 ESTADO VARCHAR2(20) DEFAULT 'PREPARADO' NOT NULL
  CHECK (ESTADO IN ('PREPARADO','EN_RUTA','ENTREGADO','INCIDENCIA')),
 FECHA_PREPARACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 FECHA_SALIDA TIMESTAMP,
 FECHA_ENTREGA TIMESTAMP,
 OBSERVACIONES VARCHAR2(300)
);
CREATE TABLE DETALLE_DESPACHO (
 ID_DETALLE_DESPACHO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ID_DESPACHO NUMBER NOT NULL REFERENCES DESPACHO(ID_DESPACHO),
 ID_PRODUCTO NUMBER NOT NULL REFERENCES PRODUCTO(ID_PRODUCTO),
 CANTIDAD NUMBER(14,3) NOT NULL CHECK (CANTIDAD > 0),
 CONSTRAINT UQ_DET_DESP_PROD UNIQUE(ID_DESPACHO, ID_PRODUCTO)
);

-- Reserva de producto final para evitar comprometer stock dos veces.
ALTER TABLE INVENTARIO ADD (
 CANTIDAD_RESERVADA NUMBER(14,3) DEFAULT 0 NOT NULL,
 CONSTRAINT CHK_INV_RES_F1 CHECK(CANTIDAD_RESERVADA >= 0),
 CONSTRAINT CHK_INV_CAN_F1 CHECK(CANTIDAD >= 0),
 CONSTRAINT CHK_INV_RES_CAN_F1 CHECK(CANTIDAD_RESERVADA <= CANTIDAD),
 CONSTRAINT CHK_INV_MIN_F1 CHECK(EXISTENCIA_MINIMA >= 0)
);

-- Vistas de solo lectura, útiles para reportes y API REST.
CREATE OR REPLACE VIEW VW_STOCK_DISPONIBLE AS
 SELECT p.ID_PRODUCTO,p.NOMBRE,p.TIPO,u.ABREVIATURA UNIDAD,
        i.CANTIDAD,i.CANTIDAD_RESERVADA,
        (i.CANTIDAD-i.CANTIDAD_RESERVADA) DISPONIBLE,
        i.EXISTENCIA_MINIMA,
        CASE WHEN i.CANTIDAD-i.CANTIDAD_RESERVADA < i.EXISTENCIA_MINIMA
             THEN 'BAJO' ELSE 'NORMAL' END ALERTA
 FROM INVENTARIO i JOIN PRODUCTO p ON p.ID_PRODUCTO=i.ID_PRODUCTO
 JOIN UNIDAD_MEDIDA u ON u.ID_UNIDAD_MEDIDA=p.ID_UNIDAD_MEDIDA
 WHERE i.ESTADO='A' AND p.ESTADO='A';

CREATE OR REPLACE VIEW VW_PEDIDOS_RESUMEN AS
 SELECT pe.ID_PEDIDO,s.NOMBRE SUCURSAL, ep.NOMBRE ESTADO,
        j.NOMBRE JORNADA,pe.FECHA_PEDIDO,
        COUNT(dp.ID_DETALLE_PEDIDO) LINEAS,
        NVL(SUM(dp.CANTIDAD),0) UNIDADES_PEDIDAS
 FROM PEDIDO pe JOIN SUCURSAL s ON pe.ID_SUCURSAL=s.ID_SUCURSAL
 JOIN ESTADO_PEDIDO ep ON pe.ID_ESTADO_PEDIDO=ep.ID_ESTADO_PEDIDO
 JOIN JORNADA j ON pe.ID_JORNADA=j.ID_JORNADA
 LEFT JOIN DETALLE_PEDIDO dp ON pe.ID_PEDIDO=dp.ID_PEDIDO
 GROUP BY pe.ID_PEDIDO,s.NOMBRE,ep.NOMBRE,j.NOMBRE,pe.FECHA_PEDIDO;

