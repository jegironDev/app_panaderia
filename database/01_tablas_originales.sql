--========================================================================================
--  Catalogos y tablas sin dependencias
--  UNIDAD_MEDIDA | JORNADA | ESTADO_PEDIDO | RUTA | SUCURSAL | PROVEEDOR
--========================================================================================

--  UNIDADA_MEDIDA
--  Unidades de medida para utilizarse en PRODUCTO | DETALLE_RECETA | DETALLE_COMPRA
--  Ejemplo:
--  Nombre: Kilogramo
--  Abreviatura: Kg
--  Estado: A | I (Activo | Inactivo)
--  (cambia si se decide dejar de utilizar alguna y hacer un borrado logico)

CREATE TABLE UNIDAD_MEDIDA (
    ID_UNIDAD_MEDIDA  NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_UMED PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL,
    ABREVIATURA VARCHAR2(10) NOT NULL,
    ESTADO CHAR(1) DEFAULT 'A' NOT NULL
        CONSTRAINT CHK_UMED_ESTADO CHECK (ESTADO IN ('A','I'))
);

--  JORNADA
--  Jornadas de despacho:
--  MAÑANA | MEDIO DIA | TARDE para utilizarse en PEDIDO
CREATE TABLE JORNADA (
    ID_JORNADA  NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_JOR PRIMARY KEY,
    NOMBRE VARCHAR2(30) NOT NULL,
    ESTADO CHAR(1) DEFAULT 'A' NOT NULL
        CONSTRAINT CHK_JOR_ESTADO CHECK (ESTADO IN ('A','I'))
);

--  ESTADO_PEDIDO
--  Estados del flujo de un pedido:
--  PENDIENTE | DESPACHADO | EN_RUTA | ENTREGADO | PROBLEMA | etc...
CREATE TABLE ESTADO_PEDIDO (
    ID_ESTADO_PEDIDO NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_EPED PRIMARY KEY,
    NOMBRE VARCHAR2(30) NOT NULL,
    DESCRIPCION VARCHAR2(150),
    ESTADO CHAR(1) DEFAULT 'A' NOT NULL
        CONSTRAINT CHK_EPED_ESTADO CHECK (ESTADO IN ('A','I'))
);

--  RUTA
--  Catalogo de rutas: 1, 2, 3, SUR, NORTE, CA-9, etc...
--  Para utilizarse en PEDIDO
CREATE TABLE RUTA (
    ID_RUTA NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_RUTA PRIMARY KEY,
    NOMBRE VARCHAR2(60) NOT NULL,
    DESCRIPCION VARCHAR2(150),
    ESTADO CHAR(1) DEFAULT 'A' NOT NULL
        CONSTRAINT CHK_RUTA_ESTADO CHECK (ESTADO IN ('A','I'))
);

--  SUCURSAL
--  Para utilizarse en: 
--  USUARIO | PEDIDO | DETALLE_RUTA | BITACORA_SUCURSALES
--  ESTADO para validar estado de la sucursal: 
--  A | I | B (Activo | Inactivo | DADA DE BAJA)
CREATE TABLE SUCURSAL (
    ID_SUCURSAL NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_SUC PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    DIRECCION VARCHAR2(200),
    TELEFONO VARCHAR2(15),
    ESTADO CHAR(1) DEFAULT 'A' NOT NULL
        CONSTRAINT CHK_SUC_ESTADO CHECK (ESTADO IN ('A','I','B'))
);

--  PROVEEDOR
CREATE TABLE PROVEEDOR (
    ID_PROVEEDOR NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_PROV PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    NIT VARCHAR2(20),
    TELEFONO VARCHAR2(15),
    DIRECCION VARCHAR2(200),
    ESTADO CHAR(1) DEFAULT 'A' NOT NULL
        CONSTRAINT CHK_PROV_ESTADO CHECK (ESTADO IN ('A','I'))
);

--========================================================================================
--  Tablas con dependencias
--========================================================================================

--  PRODUCTO
--  TIPO: PFI | MAT | INS (PRODUCTO FINAL | MATERIALES | INSUMOS)
CREATE TABLE PRODUCTO (
    ID_PRODUCTO NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_PROD PRIMARY KEY,
    ID_UNIDAD_MEDIDA NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    TIPO VARCHAR2(10) NOT NULL
        CONSTRAINT CHK_PROD_TIPO CHECK (TIPO IN ('PFI','MAT','INS')),
    PRECIO NUMBER(12,2) DEFAULT 0 NOT NULL,
    ESTADO CHAR(1) DEFAULT 'A' NOT NULL
        CONSTRAINT CHK_PROD_ESTADO CHECK (ESTADO IN ('A','I')),
    
    CONSTRAINT FK_PROD_UMED FOREIGN KEY (ID_UNIDAD_MEDIDA)
            REFERENCES UNIDAD_MEDIDA (ID_UNIDAD_MEDIDA)
);

--  USUARIO
--  TIPO: 
--  ADMIN (Gerencia, control total)
--  OPERATIVO (Control de compras, inventario, pedidos, envios, etc...)
--  ESTANDAR (Para los usuarios de las sucursales que haran los pedidos)
--  ID_SUCURSAL para identificar a que sucursal pertenece un usuario
--  (NULL para los usuario que pertenecen a la fabrica)
--  REQUIERE_CAMBIO_PSWD para forzar el cambio de contraseña en el primer inicio:
--  S | N (SI | NO)
--  INICIOS_FALLIDOS para control de inicios de sesion fallidos
--  BLOQUEADO para bloquear usuarios al superar inicios de sesion fallidos:
--  S | N (SI | NO)
--  ESTADO para validar estado de la cuenta: 
--  A | I | B (Activo | Inactivo | DADO DE BAJA)
CREATE TABLE USUARIO (
    ID_USUARIO NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_USR PRIMARY KEY,
        ID_SUCURSAL NUMBER,
        USUARIO VARCHAR2(50)  NOT NULL
            CONSTRAINT UQ_USR_USUARIO UNIQUE,
        PRIMER_NOMBRE VARCHAR2(50)  NOT NULL,
        SEGUNDO_NOMBRE VARCHAR2(50),
        PRIMER_APELLIDO VARCHAR2(50)  NOT NULL,
        SEGUNDO_APELLIDO VARCHAR2(50),
        PSWD VARCHAR2(200) NOT NULL,
        PUESTO VARCHAR2(60),
        TIPO VARCHAR2(10) NOT NULL
            CONSTRAINT CHK_USR_TIPO CHECK (TIPO IN ('ADMIN','OPERATIVO','ESTANDAR')),
        REQUIERE_CAMBIO_PSWD CHAR(1) DEFAULT 'S' NOT NULL
            CONSTRAINT CHK_USR_REQCAMBIO CHECK (REQUIERE_CAMBIO_PSWD IN ('S','N')),
        INICIOS_FALLIDOS NUMBER DEFAULT 0 NOT NULL,
        BLOQUEADO CHAR(1) DEFAULT 'N' NOT NULL
            CONSTRAINT CHK_USR_BLOQUEADO CHECK (BLOQUEADO IN ('S','N')),
        ESTADO CHAR(1) DEFAULT 'A' NOT NULL
            CONSTRAINT CHK_USR_ESTADO CHECK (ESTADO IN ('A','I','B')),
            
        CONSTRAINT FK_USR_SUC FOREIGN KEY (ID_SUCURSAL)
             REFERENCES SUCURSAL (ID_SUCURSAL)
);

--  DETALLE_RUTA
--  Sucursales que cubre cada ruta y el orden de entrega
--  Estado: A | I (Activo | Inactivo)
CREATE TABLE DETALLE_RUTA (
    ID_DETALLE_RUTA NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_DRUT PRIMARY KEY,
    ID_RUTA NUMBER  NOT NULL,
    ID_SUCURSAL NUMBER  NOT NULL,
    ORDEN_ENTREGA NUMBER NOT NULL,
    ESTADO CHAR(1) DEFAULT 'A' NOT NULL
        CONSTRAINT CHK_DRUT_ESTADO CHECK (ESTADO IN ('A','I')),
    
    CONSTRAINT UQ_IDRUT_IDSUC UNIQUE (ID_RUTA, ID_SUCURSAL),
    
    CONSTRAINT FK_DRUT_RUT FOREIGN KEY (ID_RUTA)
        REFERENCES RUTA (ID_RUTA),
    CONSTRAINT FK_DRUT_SUC FOREIGN KEY (ID_SUCURSAL)
        REFERENCES SUCURSAL (ID_SUCURSAL)
);

--  RECETA
--  Cuantos panes se producen con cada Receta/Lote
--  ID_PRODUCTO: Tipo de pan que se produce
--  UNIDADES_PRODUCIDAS: Cuantos panes se producen con la receta
CREATE TABLE RECETA (
    ID_RECETA NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_REC PRIMARY KEY,
    ID_PRODUCTO NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    UNIDADES_PRODUCIDAS NUMBER(14,3)  NOT NULL
        CONSTRAINT CHK_REC_UNIDADES CHECK (UNIDADES_PRODUCIDAS > 0),
    ESTADO CHAR(1) DEFAULT 'A' NOT NULL
        CONSTRAINT CHK_REC_ESTADO CHECK (ESTADO IN ('A','I')),
    
    CONSTRAINT FK_REC_PROD FOREIGN KEY (ID_PRODUCTO)
             REFERENCES PRODUCTO (ID_PRODUCTO)
);

--  INVENTARIO
--  Existencia actual de cada produto (PRODUCTO FINAL | MATERIAL | INSUMO)
--  CONSTRAINT UQ_INV_PRODUCTO UNIQUE (forzar inventario para un producto)
CREATE TABLE INVENTARIO (
    ID_INVENTARIO NUMBER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_INV PRIMARY KEY,
    ID_PRODUCTO NUMBER NOT NULL
        CONSTRAINT UQ_INV_PRODUCTO UNIQUE,
    CANTIDAD NUMBER(14,3)  DEFAULT 0 NOT NULL,
    EXISTENCIA_MINIMA NUMBER(14,3)  DEFAULT 0 NOT NULL,
    ESTADO CHAR(1) DEFAULT 'A' NOT NULL
        CONSTRAINT CHK_INV_ESTADO CHECK (ESTADO IN ('A','I')),
    
    CONSTRAINT FK_INV_PROD FOREIGN KEY (ID_PRODUCTO)
        REFERENCES PRODUCTO (ID_PRODUCTO)
);

--  DETALLE_RECETA
--  ID_PRODUCTO: Material | Insumos que consume cada receta, unidad de medida y cantidad
CREATE TABLE DETALLE_RECETA (
    ID_DETALLE_RECETA NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_DREC PRIMARY KEY,
    ID_RECETA NUMBER NOT NULL,
    ID_PRODUCTO NUMBER NOT NULL,
    ID_UNIDAD_MEDIDA NUMBER NOT NULL,
    CANTIDAD NUMBER(14,3) NOT NULL
        CONSTRAINT CHK_DREC_CANTIDAD CHECK (CANTIDAD > 0),
        
    CONSTRAINT FK_DREC_REC  FOREIGN KEY (ID_RECETA)
        REFERENCES RECETA (ID_RECETA),
    CONSTRAINT FK_DREC_PROD FOREIGN KEY (ID_PRODUCTO)
        REFERENCES PRODUCTO (ID_PRODUCTO),
    CONSTRAINT FK_DREC_UMED FOREIGN KEY (ID_UNIDAD_MEDIDA)
        REFERENCES UNIDAD_MEDIDA (ID_UNIDAD_MEDIDA)
);

--========================================================================================
--  Tablas de Operacion: PEDIDOS | PRODUCCION | COMPRAS y sus DETALLES
--========================================================================================

--  PEDIDO
--  FK Obligatorias:
--  SUCURSAL | USUARIO | JORNADA | ESTADO_PEDIDO
--  FK Opcional:
--  RUTA: opcional al crear el pedido, se asigna luego al programar las rutas, permite NULL
CREATE TABLE PEDIDO (
    ID_PEDIDO NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_PED PRIMARY KEY,
    ID_SUCURSAL NUMBER  NOT NULL,
    ID_USUARIO NUMBER  NOT NULL,
    ID_RUTA NUMBER,
    ID_JORNADA NUMBER  NOT NULL,
    ID_ESTADO_PEDIDO NUMBER  NOT NULL,
    FECHA_PEDIDO DATE DEFAULT SYSDATE NOT NULL,
    FECHA_DESPACHO DATE,
    OBSERVACIONES VARCHAR2(300),
    
    CONSTRAINT FK_PED_SUC FOREIGN KEY (ID_SUCURSAL)
        REFERENCES SUCURSAL (ID_SUCURSAL),
    CONSTRAINT FK_PED_USR FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_PED_RUT FOREIGN KEY (ID_RUTA)
        REFERENCES RUTA (ID_RUTA),
    CONSTRAINT FK_PED_JOR FOREIGN KEY (ID_JORNADA)
        REFERENCES JORNADA (ID_JORNADA),
    CONSTRAINT FK_PED_EPED FOREIGN KEY (ID_ESTADO_PEDIDO)
        REFERENCES ESTADO_PEDIDO (ID_ESTADO_PEDIDO)
);

--  DETALLE_PEDIDO
--  Tipo de producto final y cantidad que pide cada sucursal
CREATE TABLE DETALLE_PEDIDO (
    ID_DETALLE_PEDIDO NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_DPED PRIMARY KEY,
    ID_PEDIDO NUMBER NOT NULL,
    ID_PRODUCTO NUMBER NOT NULL,
    CANTIDAD NUMBER(14,3) NOT NULL
        CONSTRAINT CHK_DPED_CANTIDAD CHECK (CANTIDAD > 0),
        
    CONSTRAINT FK_DPED_PED  FOREIGN KEY (ID_PEDIDO)
        REFERENCES PEDIDO (ID_PEDIDO),
    CONSTRAINT FK_DPED_PROD FOREIGN KEY (ID_PRODUCTO)
        REFERENCES PRODUCTO (ID_PRODUCTO)
);

--  PRODUCCION
--  Registro de cada produccion
--  Referencia a la receta usada y el usuario que registro la produccion
--  CANTIDAD_PRODUCIDA guarda las unidades producidas calculando 
--  CANTIDAD_LOTES*UNIDADES_PRODUCIDAS de la tabla RECETA
CREATE TABLE PRODUCCION (
    ID_PRODUCCION NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_PRODUC PRIMARY KEY,
    ID_RECETA NUMBER NOT NULL,
    ID_USUARIO NUMBER NOT NULL,
    CANTIDAD_LOTES NUMBER(14,3)  NOT NULL
        CONSTRAINT CHK_PRODUC_LOTES CHECK (CANTIDAD_LOTES > 0),
    CANTIDAD_PRODUCIDA NUMBER(14,3) NOT NULL,
    FECHA DATE DEFAULT SYSDATE NOT NULL,
    
    CONSTRAINT FK_PRODUCCION_REC FOREIGN KEY (ID_RECETA)
        REFERENCES RECETA (ID_RECETA),
    CONSTRAINT FK_PRODUCCION_USR FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO)
);

--  COMPRA
--  DOCUMENTO: No. de factura de la compra
CREATE TABLE COMPRA (
    ID_COMPRA NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_COM PRIMARY KEY,
    ID_PROVEEDOR NUMBER NOT NULL,
    ID_USUARIO NUMBER NOT NULL,
    DOCUMENTO VARCHAR2(50),
    FECHA DATE DEFAULT SYSDATE NOT NULL,
    TOTAL NUMBER(14,2) DEFAULT 0 NOT NULL,
    ESTADO CHAR(1) DEFAULT 'A' NOT NULL
        CONSTRAINT CHK_COM_ESTADO CHECK (ESTADO IN ('A','I')),
    
    CONSTRAINT FK_COM_PROV FOREIGN KEY (ID_PROVEEDOR)
        REFERENCES PROVEEDOR (ID_PROVEEDOR),
    CONSTRAINT FK_COM_USR FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO)
);

--  DETALLE_COMPRA
--  Materiales | Insumos y cuanto se compro, con precio unitario
CREATE TABLE DETALLE_COMPRA (
    ID_DETALLE_COMPRA NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_DCOM PRIMARY KEY,
    ID_COMPRA NUMBER NOT NULL,
    ID_PRODUCTO NUMBER NOT NULL,
    ID_UNIDAD_MEDIDA NUMBER NOT NULL,
    CANTIDAD NUMBER(14,3) NOT NULL
        CONSTRAINT CHK_DCOM_CANTIDAD CHECK (CANTIDAD > 0),
    PRECIO_UNITARIO NUMBER(12,2) NOT NULL,
    SUBTOTAL NUMBER(14,2) NOT NULL,
    
    CONSTRAINT FK_DCOM_COM FOREIGN KEY (ID_COMPRA)
        REFERENCES COMPRA (ID_COMPRA),
    CONSTRAINT FK_DCOM_PROD FOREIGN KEY (ID_PRODUCTO)
        REFERENCES PRODUCTO (ID_PRODUCTO),
    CONSTRAINT FK_DCOM_UMED FOREIGN KEY (ID_UNIDAD_MEDIDA)
        REFERENCES UNIDAD_MEDIDA (ID_UNIDAD_MEDIDA)
);

--  DETALLE_INVENTARIO
--  ORIGEN: accion que produce el cambio en el inventario
--  COMPRA | PRODUCCION | PEDIDO | AJUSTE
--  ID_REFERENCIA: guarda el ID de la accion que produce el cambio
CREATE TABLE DETALLE_INVENTARIO (
    ID_DETALLE_INVENTARIO NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_DINV PRIMARY KEY,
    ID_INVENTARIO NUMBER NOT NULL,
    ID_USUARIO NUMBER NOT NULL,
    ORIGEN VARCHAR2(20) NOT NULL
        CONSTRAINT CHK_DINV_ORIGEN CHECK (ORIGEN IN ('COMPRA','PRODUCCION','PEDIDO','AJUSTE')),
    ID_REFERENCIA NUMBER,
    TIPO_MOVIMIENTO VARCHAR2(10) NOT NULL
        CONSTRAINT CHK_DINV_TIPOMOV CHECK (TIPO_MOVIMIENTO IN ('ENTRADA','SALIDA')),
    EXISTENCIA_ANTERIOR NUMBER(14,3) NOT NULL,
    EXISTENCIA_NUEVA NUMBER(14,3) NOT NULL,
    FECHA DATE DEFAULT SYSDATE NOT NULL,
    
    CONSTRAINT FK_DINV_INV FOREIGN KEY (ID_INVENTARIO)
        REFERENCES INVENTARIO (ID_INVENTARIO),
    CONSTRAINT FK_DINV_USR FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO)
);


--========================================================================================
--  Tablas para Bitacoras
--========================================================================================

--  BITACORA_USUARIOS
--  Registro sobre la gestion de usuarios
--  ID_USUARIO: usuario que realiza la accion
--  ID_USUARIO_AFECTADO: usuario sobre el que se realiza la accion
--  (2 FOREING KEY de la tabla USUARIO)
--  ACCION: CREADO | MODIFICADO | DESBLOQUEADO | DADO_DE_BAJA | etc...
CREATE TABLE BITACORA_USUARIOS (
    ID_BITACORA_USUARIOS NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_BUSR PRIMARY KEY,
    ID_USUARIO NUMBER NOT NULL,
    ID_USUARIO_AFECTADO NUMBER NOT NULL,
    ACCION VARCHAR2(50) NOT NULL,
    FECHA_HORA DATE DEFAULT SYSDATE NOT NULL,
    COMENTARIO VARCHAR2(300),
    
    CONSTRAINT FK_BUSR_USR_AUTOR FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_BUSR_USR_AFEC FOREIGN KEY (ID_USUARIO_AFECTADO)
        REFERENCES USUARIO (ID_USUARIO)
);

-- BITACORTA_SESIONES
-- Cuando inicio y cerro sesion cada usuario
CREATE TABLE BITACORA_SESIONES (
    ID_SESION NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_BSES PRIMARY KEY,
    ID_USUARIO NUMBER NOT NULL,
    FECHA_HORA_INICIO DATE DEFAULT SYSDATE NOT NULL,
    FECHA_HORA_CIERRE DATE,
    
    CONSTRAINT FK_BSES_USR FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO)
);

--  BITACORA SUCURSALES
--  Registro sobre la gestion de sucursales
--  ACCION: CREADA | MODIFICADA | ACTIVADA | INACTIVADA | DADA_DE_BAJA | etc...
CREATE TABLE BITACORA_SUCURSALES (
    ID_BITACORA_SUCURSALES NUMBER 
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_BSUC PRIMARY KEY,
    ID_SUCURSAL NUMBER NOT NULL,
    ID_USUARIO NUMBER NOT NULL,
    ACCION VARCHAR2(50) NOT NULL,
    FECHA_HORA DATE DEFAULT SYSDATE NOT NULL,
    COMENTARIO VARCHAR2(300),
    
    CONSTRAINT FK_BSUC_SUC FOREIGN KEY (ID_SUCURSAL)
